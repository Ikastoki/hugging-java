package com.unai.core.sintaxis.comentarios;

/*
 * COMENTARIOS DE UNA LÍNEA
 *
 * Se utilizan para escribir información o explicaciones
 * dentro del código sin que Java las ejecute.
 *
 * Se crean utilizando:
 *
 *     //
 *
 * Todo lo que aparece después de // en esa línea
 * se considera un comentario.
 */

// Ejemplos prácticos

public class Linea {

    public static void main(String[] args) {

        // Declaramos una variable
        int edad = 25;

        // Mostramos la edad por consola
        System.out.println(edad);

        int numero = 10; // También puede escribirse al final de una línea
    }
}