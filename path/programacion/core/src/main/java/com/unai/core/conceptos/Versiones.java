package com.unai.core.conceptos;

/*
##
# Versiones de Java y LTS
#
# Java evoluciona mediante nuevas versiones que incorporan características,
# mejoras de rendimiento, correcciones y cambios en la plataforma.
#
# Una versión de Java se identifica mediante un número.
#
# Por ejemplo:
#
#     Java 8
#     Java 11
#     Java 17
#     Java 21
#     Java 25
#
#
# ¿Qué significa LTS?
# -------------------
#
# LTS significa:
#
#     Long-Term Support
#
# Es decir, soporte a largo plazo.
#
# Las versiones LTS están pensadas para utilizarse durante más tiempo
# en entornos de producción y empresariales.
#
# Por eso son especialmente importantes en proyectos profesionales.
#
#
# Algunas versiones LTS importantes:
#
#     Java 8
#     Java 11
#     Java 17
#     Java 21
#     Java 25
#
# Java 17, por ejemplo, fue una versión LTS.
# Java 21 también fue una versión LTS.
#
#
# ¿Qué ocurre con las versiones que NO son LTS?
# ----------------------------------------------
#
# Java también publica versiones intermedias que tienen un ciclo de soporte
# más corto.
#
# Estas versiones permiten que nuevas características lleguen antes
# a los desarrolladores, pero normalmente no son la primera elección
# para proyectos empresariales que buscan estabilidad a largo plazo.
#
#
# CICLO MODERNO DE VERSIONES
# --------------------------
#
# Desde Java 10, Java utiliza un ciclo de lanzamiento aproximadamente
# cada seis meses.
#
# Esto significa que no tenemos que esperar varios años para recibir
# nuevas versiones del lenguaje y de la plataforma.
#
#
# ¿QUÉ VERSION ELEGIR?
# --------------------
#
# Para aprender Java actualmente es recomendable utilizar una versión LTS.
#
# En un proyecto profesional, la versión concreta dependerá de:
#
# - Requisitos del proyecto
# - Frameworks utilizados
# - Dependencias
# - Compatibilidad
# - Política de la empresa
#
# Por ejemplo, un proyecto puede utilizar Java 17 aunque exista una versión
# LTS posterior porque sus dependencias o infraestructura están preparadas
# para Java 17.
#
#
# IMPORTANTE
# ----------
#
# "La versión más nueva" no significa automáticamente
# "la versión que debemos utilizar".
#
# En entornos profesionales se suele priorizar una versión LTS
# por estabilidad, soporte y compatibilidad.
###
*/

public class Versiones {
    public static void main(String[] args) {

        // El código Java normalmente no necesita cambiar simplemente
        // porque utilicemos una versión LTS diferente.
        //
        // La compatibilidad real depende de las características utilizadas,
        // la versión del JDK y las dependencias del proyecto.

        System.out.println("Estoy utilizando Java");
    }
}
