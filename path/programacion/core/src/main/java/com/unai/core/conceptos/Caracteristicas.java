package com.unai.core.conceptos;

/*
##
# Características de Java
#
# Java tiene varias características que explican por qué se utiliza
# ampliamente en aplicaciones backend, empresariales y sistemas distribuidos.
#
# 1. Multiplataforma
# ------------------
# Java permite ejecutar el mismo bytecode en diferentes sistemas operativos
# siempre que exista una JVM compatible.
#
# Por eso Java se asocia con:
#
#     "Write Once, Run Anywhere"
#
#
# 2. Orientado a objetos
# ----------------------
# Java está diseñado alrededor de conceptos como:
#
# - Clases
# - Objetos
# - Encapsulación
# - Herencia
# - Polimorfismo
# - Abstracción
#
# Estos conceptos permiten organizar aplicaciones grandes y complejas.
#
#
# 3. Tipado estático
# ------------------
# Las variables tienen un tipo determinado.
# El compilador comprueba que las operaciones sean compatibles con esos tipos.
#
# Por ejemplo, una variable int almacena números enteros.
#
#
# 4. Fuertemente tipado
# ---------------------
# Java no permite realizar libremente operaciones entre tipos incompatibles.
#
# El compilador detecta muchos errores relacionados con los tipos antes
# de ejecutar el programa.
#
#
# 5. Gestión automática de memoria
# -------------------------------
# Java utiliza Garbage Collection (GC) para gestionar automáticamente
# gran parte de la memoria utilizada por los objetos.
#
# El programador no necesita liberar manualmente cada objeto como ocurre
# en lenguajes que utilizan gestión manual de memoria.
#
#
# 6. Robusto
# ----------
# Java incorpora mecanismos para reducir errores y facilitar la creación
# de aplicaciones fiables:
#
# - Comprobaciones en compilación
# - Sistema de excepciones
# - Tipado fuerte
# - Gestión automática de memoria
#
#
# 7. Seguro
# ---------
# Java incorpora diferentes mecanismos de seguridad en su plataforma,
# especialmente relacionados con la ejecución controlada del bytecode,
# el sistema de tipos y la gestión de memoria.
#
#
# 8. Multihilo
# ------------
# Java permite crear aplicaciones capaces de ejecutar diferentes tareas
# concurrentemente mediante hilos (threads).
#
#
# 9. Alto rendimiento
# -------------------
# Java no se limita a interpretar el bytecode de forma simple.
# La JVM puede utilizar un compilador JIT (Just-In-Time) para convertir
# partes del bytecode en código máquina optimizado durante la ejecución.
#
#
# 10. Portabilidad
# ----------------
# El bytecode generado por Java no depende directamente de una arquitectura
# concreta de CPU.
#
# La JVM se encarga de adaptar la ejecución al sistema donde se ejecuta.
#
#
# 11. Amplia biblioteca estándar
# ------------------------------
# Java proporciona una gran cantidad de clases y APIs para trabajar con:
#
# - Colecciones
# - Strings
# - Fechas
# - Entrada y salida
# - Redes
# - Concurrencia
# - Archivos
# - Utilidades
#
#
# 12. Ecosistema amplio
# ---------------------
# Java cuenta con numerosas herramientas, frameworks y bibliotecas.
#
# Algunos ejemplos conocidos son:
#
# - Spring
# - Spring Boot
# - Hibernate
# - Maven
# - Gradle
#
# Estos forman parte del ecosistema Java, pero no del lenguaje Java
# propiamente dicho.
###
*/

