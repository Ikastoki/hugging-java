package com.unai.core.conceptos;

/*
##
# Qué es Java
#
# Java es un lenguaje de programación de propósito general, orientado a objetos
# y diseñado para poder ejecutarse en diferentes sistemas operativos mediante
# la Máquina Virtual de Java (JVM).
#
# Java fue creado por Sun Microsystems y apareció públicamente en 1995.
# Actualmente Java es desarrollado y mantenido principalmente por Oracle,
# junto con una amplia comunidad y otras organizaciones.
#
# Una de sus ideas fundamentales es:
#
#     "Write Once, Run Anywhere"
#
# Es decir, escribir el código una vez y poder ejecutarlo en diferentes
# plataformas siempre que exista una JVM compatible.
#
# Java no se ejecuta directamente como código máquina del sistema operativo.
# El código fuente Java se compila a bytecode (.class), y este bytecode
# es ejecutado por la JVM.
#
# Java se utiliza en muchos ámbitos:
#
# - Aplicaciones backend
# - APIs y servicios web
# - Aplicaciones empresariales
# - Sistemas distribuidos
# - Aplicaciones Android (históricamente y todavía en determinados contextos)
# - Herramientas y aplicaciones de escritorio
#
# Java es un lenguaje:
#
# - De tipado estático: los tipos se conocen en tiempo de compilación.
# - Fuertemente tipado: las operaciones entre tipos incompatibles no se
#   realizan libremente.
# - Orientado a objetos: utiliza clases y objetos como elementos fundamentales.
# - Multiplataforma: el bytecode puede ejecutarse sobre diferentes JVM.
# - Compilado e interpretado/JIT: el código fuente se compila a bytecode
#   y la JVM utiliza diferentes mecanismos para ejecutarlo, incluido JIT.
#
# Ejemplo básico de un programa Java:
###
*/

public class QueEsJava {
    public static void main(String[] args) {

        // Este es el punto de entrada de la aplicación.
        // La ejecución comienza en el método main().
        System.out.println("Hola, Java");
    }
}
